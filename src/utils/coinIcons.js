const FALLBACK_COLORS = [
  "#E88F2B", "#22c55e", "#3b82f6", "#ef4444", "#a855f7",
  "#14b8a6", "#f59e0b", "#ec4899", "#6366f1", "#06b6d4",
];

function getColor(str) {
  let hash = 0;
  for (let i = 0; i < (str || "").length; i++) {
    hash = str.charCodeAt(i) + ((hash << 5) - hash);
  }
  return FALLBACK_COLORS[Math.abs(hash) % FALLBACK_COLORS.length];
}

function makeFallback(letter, color) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">
    <circle cx="32" cy="32" r="32" fill="${color}"/>
    <text x="32" y="32" dy=".35em" text-anchor="middle" font-family="Arial,sans-serif" font-size="24" font-weight="bold" fill="#000">${letter}</text>
  </svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

export function getCoinIcon(coinId) {
  return COIN_ICONS[coinId] || makeFallback((coinId || "?").charAt(0).toUpperCase(), getColor(coinId));
}
